// Derives the site's token and font CSS from the frozen brand kit (brand/, owned by M01).
//   node scripts/sync-brand.mjs          writes src/styles/tokens.css and src/styles/fonts.css
//   node scripts/sync-brand.mjs --check  fails if they are out of date (used in CI)
// brand/tokens/tokens.css @imports brand/fonts/fonts.css (the heavy full fonts); the site uses the reduced fonts from
// src/assets/fonts/ (scripts/reduce-fonts.py), so the @import line is dropped and the @font-face paths are changed.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url));
const read = (p) => readFile(new URL(p, `file://${root}/`), 'utf8');

const banner = (src) => `/* GENERATED by scripts/sync-brand.mjs from ${src}. Do not edit; change the brand kit through M01. */\n`;

const tokens = (await read('brand/tokens/tokens.css')).replace(/^@import url\([^)]*\);\n/m, '');
const fonts = (await read('brand/fonts/fonts.css')).replaceAll("url('./", "url('../assets/fonts/");

const outputs = {
  'site/src/styles/tokens.css': banner('brand/tokens/tokens.css') + tokens,
  'site/src/styles/fonts.css': banner('brand/fonts/fonts.css') + fonts,
};

let stale = false;
for (const [path, text] of Object.entries(outputs)) {
  const file = new URL(path, `file://${root}/`);
  if (process.argv.includes('--check')) {
    const current = await readFile(file, 'utf8').catch(() => '');
    if (current !== text) { console.error(`${path} is out of date; run: node scripts/sync-brand.mjs`); stale = true; }
  } else {
    await writeFile(file, text);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
