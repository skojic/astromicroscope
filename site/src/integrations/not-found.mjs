// Astro writes src/pages/en/404.astro to dist/en/404/index.html. Cloudflare looks for the nearest 404.html up the path,
// so move it to dist/en/404.html (the Serbian one is already dist/404.html).
//
// P07 (D59): the same build also writes the Worker's generated module. The Worker's `run_worker_first` sends the spam
// paths and every unknown path to it, so the Worker answers 404 with the 404 page itself, and 410 Gone for the 143 spam
// URLs of the old hacked site (`docs/sadrzaj/stari-sajt/spam-adrese.md`).
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SPAM_LIST = 'docs/sadrzaj/stari-sajt/spam-adrese.md';
const SITE_URL = 'https://astromicroscope.com';

/** The paths in the spam list, without the trailing slash (the Worker strips it too). */
export function spamPaths(markdown) {
  const paths = [];
  for (const line of markdown.split('\n')) {
    const match = line.match(/^https:\/\/astromicroscope\.com(\/[^\s]*)\s*$/);
    if (!match) continue;
    const path = match[1].replace(/\/+$/, '');
    if (path && !paths.includes(path)) paths.push(path);
  }
  return paths;
}

/** @returns {import('astro').AstroIntegration} */
export default function notFound() {
  return {
    name: 'am-not-found',
    hooks: {
      'astro:build:done': async ({ dir }) => {
        await rename(fileURLToPath(new URL('en/404/index.html', dir)), fileURLToPath(new URL('en/404.html', dir)));
        await rm(fileURLToPath(new URL('en/404/', dir)), { recursive: true, force: true });
        await writeWorkerModule(dir);
      },
    },
  };
}

/** The 404 pages and the spam paths, for the Worker (`src/worker/generated/not-found.ts`). */
async function writeWorkerModule(dir) {
  // src/integrations/ -> site/ (the spam list lives in the repository root: docs/sadrzaj/stari-sajt/)
  const siteRoot = fileURLToPath(new URL('../../', import.meta.url));
  const root = fileURLToPath(new URL('../../../', import.meta.url));
  const read = async (path) => readFile(fileURLToPath(new URL(path, dir)), 'utf8');
  const page = async (path) => {
    try {
      const html = await read(path);
      return JSON.stringify(html).replace(/<\/script/gi, '<\\/script');
    } catch {
      return null;
    }
  };
  const sr = await page('404.html');
  const en = await page('en/404.html');
  if (!sr || !en) throw new Error(`not-found: 404.html and en/404.html must both exist (${dir})`);
  const paths = spamPaths(await readFile(root + SPAM_LIST, 'utf8'));
  if (paths.length === 0) throw new Error(`not-found: no spam URLs in ${SPAM_LIST}`);
  const out = join(siteRoot, 'src/worker/generated/not-found.ts');
  await mkdir(join(siteRoot, 'src/worker/generated'), { recursive: true });
  const lines = [
    '// Generated by src/integrations/not-found.mjs at every build. Do not edit by hand.',
    '// The 404 pages and the spam paths the Worker answers (P07, D59).',
    'export const notFoundPages = {',
    `  sr: ${sr},`,
    `  en: ${en},`,
    '};',
    '',
    '// The spam URLs of the old hacked site, without the trailing slash (`/x/` and `/x` both match).',
    'export const spamUrls = [',
    ...paths.map((p) => `  ${JSON.stringify(p)},`),
    '];',
    '',
  ];
  await writeFile(out, lines.join('\n'), 'utf8');
}
